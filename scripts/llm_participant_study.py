def recruitment_ready(package):
    config = load(Path(package) / "recruitment.json")
    if config.get("status") != "open" or not config.get("institutional_review_determination") \
            or not config.get("closing_date"):
        raise ValueError("record institutional review determination, fixed closing date, and open recruitment first")
    closing = datetime.date.fromisoformat(config["closing_date"])
    if closing < datetime.date.today():
        raise ValueError("recruitment closing date has passed")
    return config


