def pages(package, run_dir, output):
    package, output = Path(package), Path(output)
    recruitment_ready(package)
    manifest = read_package(package)
    cases, records = records_for(package, run_dir)
    if set(cases) != {case["case_id"] for case in manifest["panels"]["comprehension"]}:
        raise ValueError("comprehension run required")
    source = validated_source(package, list(cases))
    for case_id, row in source.items():
        if any(not row[f].strip() for f in ("condition_rubric", "evidence_rubric", "action_rubric")):
            raise ValueError("independent comprehension scoring rubric required: " + case_id)
    frozen = load(package / "freeze.json")
    by_id = {r["case_id"]: r for r in records}
    output.mkdir(parents=True, exist_ok=False, mode=0o700)
    for assignment in load(package / "assignments-private.json"):
        tasks = []
        for assigned in assignment["tasks"]:
            case = cases[assigned["case_id"]]
            record = by_id[case["case_id"]]
            packet = load(package / "source-review" / f"{case['case_id']}.json")
            task = {"case_id": case["case_id"], "message": case["occurrence"]["message"],
                    "source": "\n\n".join(f"{name}\n" + "\n".join(f"{i + 1}: {line}" for i, line in enumerate(text.splitlines()))
                                           for name, text in packet["files"].items())}
            if assigned["arm"] in ("evidence", "llm"):
                task["evidence"] = "\n\n".join(s["text"] for s in packet["snippets"])
                task["evidence"] += "\nMissing context: " + json.dumps(packet["missing"])
                task["evidence"] += "\nBounded backend evidence contract (not a human verdict): " + json.dumps(
                    record["telemetry"].get("evidence_packet", {}), indent=2)
            if assigned["arm"] == "llm":
                result = record["result"]
                task["explanation"] = json.dumps({k: result[k] for k in
                    ("llm_status", "llm_assessment", "llm_actionability", "llm_explanation", "llm_why_in_this_context",
                     "llm_evidence", "llm_missing_evidence", "llm_limitations") if k in result}, indent=2)
            tasks.append(task)
        data = {"participant_id": assignment["participant_id"], "manifest_sha256": manifest["sha256"],
                "freeze_sha256": frozen["sha256"], "tasks": tasks}
        # Escape '<' so source strings cannot terminate the script element.
        encoded = json.dumps(data, ensure_ascii=True).replace("<", "\\u003c")
        target = output / f"{assignment['participant_id']}.html"
        target.write_text(PAGE.replace("__DATA__", encoded))
        target.chmod(0o600)
    return {"pages": 18, "status": "ready for consented sessions", "responses": "none collected"}


def import_responses(package, paths, output, allow_partial=False):
    package, output = Path(package), Path(output)
    manifest, frozen = read_package(package), load(package / "freeze.json")
    assignments = {a["participant_id"]: a for a in load(package / "assignments-private.json")}
    participant_ids, rows, partials = set(), [], []
    for path in paths:
        payload = load(path)
        pid = payload.get("participant_id")
        if pid not in assignments or pid in participant_ids:
            raise ValueError("unknown or duplicate participant")
        participant_ids.add(pid)
        if payload.get("manifest_sha256") != manifest["sha256"] or payload.get("freeze_sha256") != frozen["sha256"]:
            raise ValueError("response identity mismatch")
        if payload.get("consent_version") != "1" or not payload.get("consented_at"):
            raise ValueError("consent record required")
        datetime.datetime.fromisoformat(payload["consented_at"].replace("Z", "+00:00"))
        experience = payload.get("experience_years")
        if isinstance(experience, bool) or not isinstance(experience, (int, float)) or not 0 <= experience <= 60:
            raise ValueError("invalid experience")
        answers = payload.get("answers", [])
        assigned = assignments[pid]["tasks"]
        if (len(answers) != 12 and not (allow_partial and 0 <= len(answers) < 12)) \
                or [a.get("case_id") for a in answers] != [a["case_id"] for a in assigned[:len(answers)]]:
            raise ValueError("missing, duplicated, or out-of-order tasks")
        current_rows = []
        for answer, task in zip(answers, assigned):
            seconds = answer.get("elapsed_seconds")
            confidence = answer.get("confidence")
            if isinstance(seconds, bool) or not isinstance(seconds, (int, float)) or not 0 <= seconds <= 150 \
                    or isinstance(confidence, bool) or confidence not in (1, 2, 3, 4, 5) \
                    or not isinstance(answer.get("timeout"), bool) \
                    or any(not isinstance(answer.get(f), str) for f in ("condition", "evidence", "action")):
                raise ValueError("invalid timing, confidence, timeout, or response")
            if answer["timeout"] and seconds < 149:
                raise ValueError("timeout timing inconsistent")
            current_rows.append({**answer, "participant_id": pid, "arm": task["arm"],
                                 "sequence": assignments[pid]["sequence"], "experience_years": experience})
        if len(answers) == 12:
            rows.extend(current_rows)
        else:
            partials.append({"participant_id": pid, "status": "incomplete", "answers": current_rows})
    output.mkdir(parents=True, exist_ok=False, mode=0o700)
    # Blind graders to participant ID, arm, timing and confidence.
    shuffled = rows.copy()
    random.Random(SEED + 2).shuffle(shuffled)
    mapping, grades = [], []
    for i, row in enumerate(shuffled):
        opaque = f"G{i + 1:04d}"
        mapping.append({"response_id": opaque, "participant_id": row["participant_id"], "case_id": row["case_id"]})
        save(output / "grading-packets" / f"{opaque}.json", {"response_id": opaque, "case_id": row["case_id"],
             **{f: row[f] for f in ("condition", "evidence", "action")}})
        grades.append({"response_id": opaque})
    save(output / "responses-private.json", rows)
    save(output / "partial-sessions-private.json", partials)
    save(output / "grading-mapping-private.json", mapping)
    fields = ["response_id", "condition_score", "evidence_score", "action_score", "harmful_decision", "notes"]
    for name in ("grader-A", "grader-B", "adjudication"):
        table(output / f"{name}.csv", fields, grades)
    return {"participants": len(participant_ids), "complete_sessions": len(rows) // 12,
            "partial_sessions": len(partials), "responses": len(rows), "human_scoring": "pending"}


def summarize(package, responses, grades, output):
    package, responses, grades = Path(package), Path(responses), Path(grades)
    manifest = read_package(package)
    validated_source(package, [c["case_id"] for c in manifest["panels"]["comprehension"]])
    rows = load(responses / "responses-private.json")
    if not rows:
        raise ValueError("no complete participant sessions")
    mapping = load(responses / "grading-mapping-private.json")
    indexed = {(row["participant_id"], row["case_id"]): row for row in rows}
    if len(indexed) != len(rows) or len(mapping) != len(rows) \
            or {(m["participant_id"], m["case_id"]) for m in mapping} != set(indexed):
        raise ValueError("incomplete or duplicated response/grade mapping")
    forms = [keyed_rows(grades / f"{name}.csv", ("response_id",)) for name in ("grader-A", "grader-B", "adjudication")]
    scored, agreement = [], Counter()
    for entry in mapping:
        values = []
        for form in forms:
            grade = form.get((entry["response_id"],))
            if not grade or any(grade[f] not in ("0", "1") for f in ("condition_score", "evidence_score", "action_score")) \
                    or grade["harmful_decision"] not in ("yes", "no") or not grade["notes"].strip():
                raise ValueError("independent grading/adjudication incomplete")
            values.append(grade)
        for field in ("condition_score", "evidence_score", "action_score", "harmful_decision"):
            agreement[field] += values[0][field] == values[1][field]
        row = indexed[entry["participant_id"], entry["case_id"]]
        score = sum(int(values[-1][f]) for f in ("condition_score", "evidence_score", "action_score"))
        # Do not silently assign credit to an unanswered task.
        if not any(row[f].strip() for f in ("condition", "evidence", "action")) and score:
            raise ValueError("unanswered task cannot receive credit")
        scored.append({**row, "score": score, "harmful_decision": values[-1]["harmful_decision"]})
    groups = {}
    for arm in ARMS:
        selected = [r for r in scored if r["arm"] == arm]
        groups[arm] = {"tasks": len(selected), "mean_score_out_of_3": statistics.mean(r["score"] for r in selected),
                       "median_seconds": statistics.median(r["elapsed_seconds"] for r in selected),
                       "timeouts": sum(r["timeout"] for r in selected),
                       "harmful_decisions": sum(r["harmful_decision"] == "yes" for r in selected)}
    def differences(key):
        result = []
        for value in sorted({r[key] for r in scored}):
            means = {arm: [r for r in scored if r[key] == value and r["arm"] == arm] for arm in ARMS}
            if all(means.values()):
                result.append({key: value, "score_difference_llm_minus_evidence":
                    statistics.mean(r["score"] for r in means["llm"]) - statistics.mean(r["score"] for r in means["evidence"]),
                    "time_difference_llm_minus_evidence": statistics.mean(r["elapsed_seconds"] for r in means["llm"]) -
                    statistics.mean(r["elapsed_seconds"] for r in means["evidence"])})
        return result
    n = len({r["participant_id"] for r in scored})
    sequences = dict(Counter(r["sequence"] for r in scored if r["case_id"] == scored[0]["case_id"]))
    save(output, {"participants": n, "status": "exploratory" if 12 <= n <= 18 else "feasibility-only",
         "groups": groups, "participant_differences": differences("participant_id"),
         "task_differences": differences("case_id"), "sequence_counts": sequences,
         "grading_agreement": {f: count / len(rows) for f, count in agreement.items()},
         "partial_sessions": len(load(responses / "partial-sessions-private.json")),
         "interpretation": "Descriptive participant- and task-level contrasts; no independent-task significance test or assumed benefit."})
    return {"participants": n, "output": str(output)}
