def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _write_report(validation_dir: Path, report: dict[str, Any]) -> None:
    json_path = validation_dir / "validation-integrity.json"
    md_path = validation_dir / "VALIDATION_INTEGRITY_REPORT.md"
    json_path.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    lines = [
        "# V0.0.7 validation package integrity report",
        "",
        f"Audit time: `{report['created_at_utc']}`",
        f"Stage: `{report['stage']}`",
        f"Result: **{'PASS' if report['passed'] else 'FAIL'}**",
        "",
        "This report validates the frozen agreement-pilot handoff only. It is not a detector-accuracy report.",
        "",
        "## Pilot counts",
        "",
        "| Family | Selected rows | Distinct repositories |",
        "|---|---:|---:|",
    ]
    for family in FAMILY_ORDER:
        lines.append(
            f"| {FAMILY_NAMES[family]} | {report['counts']['by_family'].get(FAMILY_NAMES[family], 0)} "
            f"| {report['counts']['repositories_by_family'].get(family, 0)} |"
        )
    lines.extend(
        [
            "",
            f"Total blank independent reviewer rows: **{report['counts'].get('row_count', 0)} per reviewer**.",
            f"Frozen context bundles: **{report['counts'].get('context_count', 0)}**.",
            "",
            "## Checks",
            "",
        ]
    )
    for name, check in report["checks"].items():
        lines.append(f"- [{'x' if check['passed'] else ' '}] `{name}` — {check['detail']}")
    lines.extend(
        [
            "",
            "## Boundaries",
            "",
            "- Human labels: none created; both reviewer decision areas are blank.",
            f"- The identical {report['counts'].get('ai_shadow_row_count', 0)}-row AI-shadow template is present, but every AI decision field is blank; formal AI labeling waits for frozen human gold.",
            "- Heldout: no heldout occurrence rows or contexts were opened/emitted.",
            f"- Review/history context-eligible cases: {report['sampling'].get('review_usable_total', 0)}. Missing actual parents are allowed for message-only rules; missing parents for diff-dependent rules are excluded.",
            "- Pilot items are permanently excluded from performance scoring.",
            "- Primary calibration, source-first recall, threshold, and heldout samples are not generated by this audit.",
            "",
        ]
    )
    if report["failures"]:
        lines.extend(["## Failures", ""])
        lines.extend(f"- {failure}" for failure in report["failures"])
        lines.append("")
    md_path.write_text("\n".join(lines), encoding="utf-8")

    sampling = report["sampling"]
    audit_lines = [
        "# V0.0.7 sampling audit — agreement pilot",
        "",
        f"Audit time: `{report['created_at_utc']}`",
        f"Integrity result: **{'PASS' if report['passed'] else 'FAIL'}**",
        "",
        "This is the calibration-only agreement pilot. It is not a representative precision sample, recall panel, threshold sample, or heldout evaluation.",
        "",
        "## Frozen populations",
        "",
        f"- Detector-quality repository universe: {sampling['analyzable_repositories']} ({sampling['calibration_repositories']} calibration / {sampling['heldout_repositories']} heldout).",
        f"- Full static-source occurrence universe: {sampling['full_static_source_candidates']:,}.",
        f"- Static-source candidates in calibration repositories: {sampling['calibration_static_source_candidates']:,}.",
        f"- Static-source candidates in heldout repositories: {sampling['heldout_static_source_candidates']:,}; no heldout rows/contexts were emitted.",
        f"- Agreement-pilot workload: {report['counts']['row_count']} rows for Reviewer A and the same {report['counts']['row_count']} rows for Reviewer B.",
        "",
        "## Pilot counts by family, rule, and repository",
        "",
        "| Family | Rule | Source candidates | Context-eligible | Missing first parent | Missing required parent | Selected | Eligible not selected |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for item in sampling["by_family_rule"]:
        audit_lines.append(
            f"| {item['family']} | `{item['rule_id']}` | {item['source_candidates']} | "
            f"{item['context_eligible']} | {item['missing_parent']} | {item['missing_required_parent']} | {item['selected']} | {item['eligible_not_selected']} |"
        )
    audit_lines.extend(
        [
            "",
            "Repository-level family/rule counts, including each selected and excluded calibration repository, are in `samples/agreement-pilot/pilot-selection-audit.csv`. The full nested counts also appear in the pilot manifest.",
            "",
            "## Family and reviewer workload summary",
            "",
            "| Family | Calibration candidates with usable context | Selected | Distinct repositories selected |",
            "|---|---:|---:|---:|",
        ]
    )
    for family in FAMILY_ORDER:
        audit_lines.append(
            f"| {FAMILY_NAMES[family]} | {sampling['eligible_by_family'].get(family, 0)} "
            f"| {sampling['selected_by_family'].get(family, 0)} "
            f"| {report['counts']['repositories_by_family'].get(family, 0)} |"
        )
    audit_lines.extend(
        [
            "",
            f"Review/history source candidates: {sampling['review_source_total']}; context-eligible: {sampling['review_usable_total']}; actual first parent missing: {sampling['review_missing_parent_total']}; parent required but missing: {sampling['review_required_parent_missing_total']}. Exact commit-message evidence keeps message-only cases eligible without a parent.",
            "",
            f"AI-shadow template workload: {report['counts'].get('ai_shadow_row_count', 0)} blank rows; no AI labels have been created.",
            "",
            "## Other panels and heldout status",
            "",
            "- Representative precision core: not generated; it must wait for pilot agreement and codebook freeze.",
            "- Rule/concept/security top-ups and rare-rule performance census: not generated.",
            "- Source-first recall and threshold calibration panels: not generated. The agreement-pilot AI-shadow template is blank; formal AI labels and other-panel AI files are not generated.",
            "- Heldout samples/results: not generated; heldout contexts opened = 0.",
            f"- The selected {report['counts'].get('row_count', 0)} agreement-pilot items are permanently excluded from performance scoring.",
            "",
        ]
    )
    (validation_dir / "SAMPLING_AUDIT.md").write_text("\n".join(audit_lines), encoding="utf-8")


def validate(root: Path, validation_dir: Path) -> dict[str, Any]:
    failures: list[str] = []
    checks: dict[str, dict[str, Any]] = {}
    counts: dict[str, Any] = {}

    def record(name: str, passed: bool, detail: str) -> None:
        checks[name] = {"passed": bool(passed), "detail": detail}
        if not passed:
            failures.append(name)

    manifest_path = validation_dir / "samples/agreement-pilot/agreement-pilot-manifest.json"
    master_path = validation_dir / "samples/agreement-pilot/agreement-pilot-master.csv"
    reviewer_a_path = validation_dir / "reviewers/reviewer-a/agreement-pilot.csv"
    reviewer_b_path = validation_dir / "reviewers/reviewer-b/agreement-pilot.csv"
    ai_shadow_path = validation_dir / "reviewers/ai-shadow/agreement-pilot.csv"
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        master_bytes = master_path.read_bytes()
        reviewer_a_bytes = reviewer_a_path.read_bytes()
        reviewer_b_bytes = reviewer_b_path.read_bytes()
        ai_shadow_bytes = ai_shadow_path.read_bytes()
        master_rows = _read_csv(master_path)
        reviewer_a_rows = _read_csv(reviewer_a_path)
        reviewer_b_rows = _read_csv(reviewer_b_path)
        ai_shadow_rows = _read_csv(ai_shadow_path)
    except (OSError, json.JSONDecodeError, csv.Error) as error:
        record("pilot_files_readable", False, f"required pilot output unavailable: {error}")
        return {
            "schema_version": 1,
            "created_at_utc": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
            "stage": "agreement-pilot",
            "passed": False,
            "checks": checks,
            "counts": counts,
            "failures": failures,
        }
    record("pilot_files_readable", True, "manifest, master, both reviewer forms, and AI-shadow template are readable")

    split_path = validation_dir / "splits/repository-split.csv"
    identity_path = validation_dir / "identities/static-source-candidates.csv.gz"
    mapping_path = validation_dir / "mappings/rule-family-map.csv"
    split_hash = sha256_file(split_path)
    identity_hash = sha256_file(identity_path)
    mapping_hash = sha256_file(mapping_path)
    input_hashes_match = (
        manifest.get("inputs", {}).get("repository_split_sha256") == split_hash
        and manifest.get("inputs", {}).get("identity_index_sha256") == identity_hash
        and manifest.get("inputs", {}).get("rule_family_map_sha256") == mapping_hash
    )
    record("frozen_input_hashes", input_hashes_match, "split, identity index, and family map match the manifest")
    pilot_codebook_hashes = {
        relative: sha256_file(validation_dir / relative)
        for relative in PILOT_CODEBOOK_INPUTS
    }
    codebook_bundle_hash = _sha256_bytes(json.dumps(
        pilot_codebook_hashes, sort_keys=True, separators=(",", ":")
    ).encode("utf-8"))
    codebook_inputs_match = (
        manifest.get("inputs", {}).get("pilot_codebooks_sha256") == pilot_codebook_hashes
        and manifest.get("inputs", {}).get("pilot_codebook_bundle_sha256") == codebook_bundle_hash
    )
    record("pilot_codebook_hashes", codebook_inputs_match, "family codebooks, overrides, reviewer instructions, and pilot protocol match the frozen pilot manifest")

    split_rows = _read_csv(split_path)
    split_by_repo = {row["repository"]: row["split"] for row in split_rows}
    split_counts = Counter(split_by_repo.values())
    record(
        "repository_split",
        len(split_by_repo) == 206 and split_counts == {"calibration": 144, "heldout": 62},
        f"{len(split_by_repo)} unique repositories; {split_counts.get('calibration', 0)} calibration / {split_counts.get('heldout', 0)} heldout",
    )

    master_header = list(master_rows[0]) if master_rows else []
    reviewer_a_header = list(reviewer_a_rows[0]) if reviewer_a_rows else []
    reviewer_b_header = list(reviewer_b_rows[0]) if reviewer_b_rows else []
    ai_shadow_header = list(ai_shadow_rows[0]) if ai_shadow_rows else []
    record("master_schema", master_header == MASTER_COLUMNS, "master columns match the pilot schema")
    record(
        "reviewer_schema_and_blinding",
        reviewer_a_header == REVIEWER_COLUMNS
        and reviewer_b_header == REVIEWER_COLUMNS
        and not (set(master_header) - set(REVIEWER_VISIBLE_COLUMNS) - set(REVIEWER_DECISION_COLUMNS)) & set(reviewer_a_header),
        "reviewer forms contain only visible evidence and blank human decision fields",
    )
    record("ai_shadow_schema", ai_shadow_header == AI_SHADOW_COLUMNS, "AI-shadow template has separate AI-only decision fields")
    record(
        "ai_shadow_no_human_fields",
        not (set(REVIEWER_DECISION_COLUMNS) & set(ai_shadow_header)),
        "AI-shadow template contains no human decision columns",
    )

    sample_ids = [row.get("sample_id", "") for row in master_rows]
    occurrence_ids = [row.get("occurrence_id", "") for row in master_rows]
    record("unique_master_ids", len(sample_ids) == len(set(sample_ids)) and "" not in sample_ids, "all master sample IDs are unique and nonempty")
    record("unique_occurrence_ids", len(occurrence_ids) == len(set(occurrence_ids)) and "" not in occurrence_ids, "each selected occurrence appears once")
    record(
        "reviewer_rows_match_master",
        len(reviewer_a_rows) == len(master_rows)
        and len(reviewer_b_rows) == len(master_rows)
        and [row.get("sample_id") for row in reviewer_a_rows] == sample_ids
        and [row.get("sample_id") for row in reviewer_b_rows] == sample_ids,
        "Reviewer A and B have the exact master IDs and row order",
    )
    record(
        "ai_shadow_rows_match_master",
        len(ai_shadow_rows) == len(master_rows)
        and [row.get("sample_id") for row in ai_shadow_rows] == sample_ids,
        "blank AI-shadow template has the exact master IDs and row order",
    )
    immutable_match = True
    for reviewer_rows in (reviewer_a_rows, reviewer_b_rows):
        if len(reviewer_rows) != len(master_rows):
            immutable_match = False
            continue
        for master_row, reviewer_row in zip(master_rows, reviewer_rows):
            if any(reviewer_row.get(column) != master_row.get(column) for column in REVIEWER_VISIBLE_COLUMNS):
                immutable_match = False
                break
    record("reviewer_evidence_matches_master", immutable_match, "all visible reviewer fields match the frozen master")
    record("reviewer_forms_identical", reviewer_a_bytes == reviewer_b_bytes, "independent blank forms have identical bytes")
    ai_visible_match = len(ai_shadow_rows) == len(master_rows) and all(
        ai_row.get(column) == master_row.get(column)
        for master_row, ai_row in zip(master_rows, ai_shadow_rows)
        for column in REVIEWER_VISIBLE_COLUMNS
    )
    record("ai_shadow_evidence_matches_master", ai_visible_match, "AI-shadow template has the same visible evidence")
    decisions_blank = all(
        not row.get(column, "")
        for rows in (reviewer_a_rows, reviewer_b_rows)
        for row in rows
        for column in REVIEWER_DECISION_COLUMNS
    )
    record("no_human_labels_yet", decisions_blank and manifest.get("human_labels_created") is False, "all human decision fields are blank")
    ai_blank = all(not row.get(column, "") for row in ai_shadow_rows for column in AI_DECISION_COLUMNS)
    record("no_ai_labels_yet", ai_blank and manifest.get("ai_labels_created") is False, "all AI-shadow decision fields are blank")

    family_counts = Counter(row.get("review_family", "") for row in master_rows)
    expected_family_counts = {
        FAMILY_NAMES[family]: manifest.get("selection", {}).get("selected_counts_by_family", {}).get(family, -1)
        for family in FAMILY_ORDER
    }
    record("family_targets", dict(family_counts) == expected_family_counts, f"selected family counts: {dict(family_counts)}")
    counts["by_family"] = dict(sorted(family_counts.items()))
    counts["repositories_by_family"] = {
        family: len({row["repository"] for row in master_rows if row["review_family"] == FAMILY_NAMES[family]})
        for family in FAMILY_ORDER
    }
    counts["row_count"] = len(master_rows)
    counts["ai_shadow_row_count"] = len(ai_shadow_rows)

    calibration_only = all(split_by_repo.get(row.get("repository", "")) == "calibration" for row in master_rows)
    record("calibration_only_selection", calibration_only, "every selected repository is in the calibration split")
    flags_correct = all(
        row.get("is_agreement_pilot") == "true" and row.get("eligible_for_performance_scoring") == "false"
        for row in master_rows
    ) and manifest.get("eligible_for_performance_scoring") is False
    record("pilot_scoring_exclusion", flags_correct, "every item is marked pilot-only and ineligible for performance scoring")
    no_hidden_fields = not ({"severity", "confidence", "sampling_weight", "selection_probability", "ai_label", "other_reviewer_label"} & set(reviewer_a_header))
    record("blinding_fields_absent", no_hidden_fields, "reviewer schemas omit severity, confidence, weights, AI, and other-reviewer fields")

    heldout = manifest.get("heldout_protection", {})
    heldout_closed = (
        heldout.get("heldout_contexts_opened") == 0
        and heldout.get("heldout_occurrence_rows_emitted") == 0
        and heldout.get("selected_rows_from_heldout") == 0
    )
    record("heldout_protection", heldout_closed, "manifest records zero heldout contexts, emitted rows, and selections")

    expected_files = manifest.get("files", {})
    file_hashes_ok = bool(expected_files)
    listed_paths: set[Path] = set()
    for relative, expected in expected_files.items():
        path = (validation_dir / relative).resolve()
        if validation_dir.resolve() not in path.parents or not path.is_file():
            file_hashes_ok = False
            continue
        listed_paths.add(path)
        raw = path.read_bytes()
        if len(raw) != expected.get("bytes") or _sha256_bytes(raw) != expected.get("sha256"):
            file_hashes_ok = False
    record("generated_file_hashes", file_hashes_ok, f"{len(expected_files)} output/context files match manifest checksums")
    record(
        "ai_shadow_template_hash",
        manifest.get("ai_shadow_template_sha256") == _sha256_bytes(ai_shadow_bytes),
        "blank AI-shadow template hash matches the manifest",
    )
    selection_audit_path = validation_dir / "samples/agreement-pilot/pilot-selection-audit.csv"
    selection_audit_rows = _read_csv(selection_audit_path) if selection_audit_path.is_file() else []
    record(
        "selection_audit_file",
        selection_audit_path.is_file()
        and len(selection_audit_rows) == manifest.get("selection_audit_row_count")
        and "samples/agreement-pilot/pilot-selection-audit.csv" in expected_files,
        f"{len(selection_audit_rows)} family/rule/repository audit rows match the manifest",
    )
    context_dir = validation_dir / "samples/agreement-pilot/context"
    expected_contexts = {path for path in listed_paths if "agreement-pilot/context" in path.as_posix()}
    actual_contexts = {path.resolve() for path in context_dir.glob("*.md")}
    record("context_bundle_inventory", actual_contexts == expected_contexts, f"{len(actual_contexts)} context files match the manifest inventory")
    counts["context_count"] = len(actual_contexts)

    safe_contexts = True
    for path in sorted(actual_contexts):
        content = path.read_text(encoding="utf-8")
        if redact_sensitive_text(content) != content:
            safe_contexts = False
            break
    for row in reviewer_a_rows:
        if redact_sensitive_text(row.get("source_context", "")) != row.get("source_context", ""):
            safe_contexts = False
            break
    record("context_redaction_idempotence", safe_contexts, "all frozen bundles and inline excerpts are stable under the redactor")

    source_counts = manifest.get("selection", {}).get("eligible_candidate_counts_by_family_repository", {})
    selected_counts = manifest.get("selection", {}).get("selected_counts_by_family_repository", {})
    excluded_counts = manifest.get("selection", {}).get("excluded_eligible_counts_by_family_repository", {})
    repo_audit_ok = True
    for family in FAMILY_ORDER:
        repos = set(source_counts.get(family, {})) | set(selected_counts.get(family, {})) | set(excluded_counts.get(family, {}))
        for repo in repos:
            eligible = source_counts.get(family, {}).get(repo, 0)
            selected = selected_counts.get(family, {}).get(repo, 0)
            excluded = excluded_counts.get(family, {}).get(repo, 0)
            if selected + excluded != eligible:
                repo_audit_ok = False
    record("family_repository_audit", repo_audit_ok, "eligible = selected + excluded counts reconcile for every family/repository")
    rule_repo_audit_ok = True
    eligible_rr = manifest.get("selection", {}).get("eligible_candidate_counts_by_family_rule_repository", {})
    selected_rr = manifest.get("selection", {}).get("selected_counts_by_family_rule_repository", {})
    excluded_rr = manifest.get("selection", {}).get("excluded_eligible_counts_by_family_rule_repository", {})
    for family in FAMILY_ORDER:
        rules = set(eligible_rr.get(family, {})) | set(selected_rr.get(family, {})) | set(excluded_rr.get(family, {}))
        for rule in rules:
            repos = set(eligible_rr.get(family, {}).get(rule, {})) | set(selected_rr.get(family, {}).get(rule, {})) | set(excluded_rr.get(family, {}).get(rule, {}))
            for repo in repos:
                eligible = eligible_rr.get(family, {}).get(rule, {}).get(repo, 0)
                selected = selected_rr.get(family, {}).get(rule, {}).get(repo, 0)
                excluded = excluded_rr.get(family, {}).get(rule, {}).get(repo, 0)
                if selected + excluded != eligible:
                    rule_repo_audit_ok = False
    record("family_rule_repository_audit", rule_repo_audit_ok, "eligible = selected + excluded counts reconcile for every family/rule/repository")

    review_rows = [row for row in master_rows if row.get("review_family") == FAMILY_NAMES["review_history"]]
    review_contexts_ok = True
    parent_pattern = re.compile(r"^- Actual first parent: `([0-9a-f]{40})`", re.MULTILINE)
    acquisition_path = root / "study/runs/v007-full-repro-2026/status/acquisition.csv"
    acquisition = {row["project"]: row for row in _read_csv(acquisition_path)}
    for row in review_rows:
        context_path = validation_dir / row["context_bundle_path"]
        context = context_path.read_text(encoding="utf-8")
        parent_match = parent_pattern.search(context)
        target = row["commit_sha"]
        if f"- Target commit: `{target}`" not in context:
            review_contexts_ok = False
            break
        repo_path = _repo_path(root, acquisition[row["repository"]])
        target_check = _git(repo_path, "rev-parse", "--verify", f"{target}^{{commit}}", check=False)
        if target_check.returncode or target_check.stdout.strip() != target:
            review_contexts_ok = False
            break
        if row["rule_id"] in REVIEW_MESSAGE_ONLY_RULE_IDS:
            if "Evidence type: exact target commit message only" not in context:
                review_contexts_ok = False
                break
            if parent_match:
                parent = parent_match.group(1)
                actual = _git(repo_path, "rev-parse", "--verify", f"{target}^1", check=False)
                if actual.returncode or actual.stdout.strip() != parent:
                    review_contexts_ok = False
                    break
        else:
            if not parent_match or "Evidence type: actual first-parent diff" not in context:
                review_contexts_ok = False
                break
            parent = parent_match.group(1)
            if f"- Diff range: `{parent}..{target}`" not in context:
                review_contexts_ok = False
                break
            actual = _git(repo_path, "rev-parse", "--verify", f"{target}^1", check=False)
            if actual.returncode or actual.stdout.strip() != parent:
                review_contexts_ok = False
                break
    record("review_history_rule_specific_evidence", review_contexts_ok, f"all {len(review_rows)} history contexts use exact message evidence or verified actual first-parent diffs as required by rule")

    selection = manifest.get("selection", {})
    candidate_by_family_rule = selection.get("eligible_candidate_counts_by_family_rule", {})
    selected_by_family_rule = selection.get("selected_counts_by_family_rule", {})
    review_source_by_rule = selection.get("review_history_source_candidate_counts_by_rule", {})
    review_missing_by_rule = selection.get("review_history_missing_first_parent_by_rule", {})
    review_required_missing_by_rule = selection.get("review_history_missing_required_first_parent_by_rule", {})
    review_usable_by_rule = selection.get("review_history_context_eligible_by_rule", {})
    by_family_rule: list[dict[str, Any]] = []
    eligible_by_family: dict[str, int] = {}
    selected_by_family: dict[str, int] = selection.get("selected_counts_by_family", {})
    for family in FAMILY_ORDER:
        if family == "review_history":
            rules = set(review_source_by_rule)
            for rule in sorted(rules):
                source_n = review_source_by_rule.get(rule, 0)
                missing_n = review_missing_by_rule.get(rule, 0)
                required_missing_n = review_required_missing_by_rule.get(rule, 0)
                usable_n = review_usable_by_rule.get(rule, 0)
                selected_n = selected_by_family_rule.get(family, {}).get(rule, 0)
                by_family_rule.append({
                    "family": FAMILY_NAMES[family],
                    "rule_id": rule,
                    "source_candidates": source_n,
                    "context_eligible": usable_n,
                    "missing_parent": missing_n,
                    "missing_required_parent": required_missing_n,
                    "selected": selected_n,
                    "eligible_not_selected": usable_n - selected_n,
                })
                if source_n != required_missing_n + usable_n:
                    record("review_history_rule_count_reconciliation", False, f"source/required-parent counts do not reconcile for {rule}")
            eligible_by_family[family] = sum(review_usable_by_rule.values())
        else:
            rule_counts = candidate_by_family_rule.get(family, {})
            selected_counts = selected_by_family_rule.get(family, {})
            for rule in sorted(set(rule_counts) | set(selected_counts)):
                eligible_n = rule_counts.get(rule, 0)
                selected_n = selected_counts.get(rule, 0)
                by_family_rule.append({
                    "family": FAMILY_NAMES[family],
                    "rule_id": rule,
                    "source_candidates": eligible_n,
                    "context_eligible": eligible_n,
                    "missing_parent": 0,
                    "missing_required_parent": 0,
                    "selected": selected_n,
                    "eligible_not_selected": eligible_n - selected_n,
                })
                if selected_n > eligible_n:
                    record("static_pilot_count_bounds", False, f"selected count exceeds calibration candidates for {rule}")
            eligible_by_family[family] = sum(rule_counts.values())

    static_source_population = json.loads(
        (validation_dir / "identities/static-source-candidates.manifest.json").read_text(encoding="utf-8")
    )["source_rows"]
    calibration_static_count = sum(
        eligible_by_family[family] for family in FAMILY_ORDER if family != "review_history"
    )
    heldout_static_count = static_source_population - calibration_static_count
    source_by_repo = selection.get("review_history_source_candidate_counts_by_repository", {})
    required_missing_by_repo = selection.get("review_history_missing_required_first_parent_by_repository", {})
    usable_by_repo = selection.get("review_history_context_eligible_by_repository", {})
    repo_review_counts_reconcile = all(
        source_by_repo.get(repository, 0) - required_missing_by_repo.get(repository, 0)
        == usable_by_repo.get(repository, 0)
        for repository in set(source_by_repo) | set(required_missing_by_repo) | set(usable_by_repo)
    )
    record("review_history_repository_count_reconciliation", repo_review_counts_reconcile, "per-repository source, required-missing-parent, and context-eligible counts reconcile")
    sampling = {
        "analyzable_repositories": len(split_by_repo),
        "calibration_repositories": split_counts.get("calibration", 0),
        "heldout_repositories": split_counts.get("heldout", 0),
        "full_static_source_candidates": static_source_population,
        "calibration_static_source_candidates": calibration_static_count,
        "heldout_static_source_candidates": heldout_static_count,
        "eligible_by_family": eligible_by_family,
        "selected_by_family": selected_by_family,
        "review_source_total": sum(review_source_by_rule.values()),
        "review_usable_total": sum(review_usable_by_rule.values()),
        "review_missing_parent_total": sum(review_missing_by_rule.values()),
        "review_required_parent_missing_total": sum(review_required_missing_by_rule.values()),
        "by_family_rule": by_family_rule,
    }

    expected_rows = (
        manifest.get("row_count") == len(master_rows) == len(reviewer_a_rows) == len(reviewer_b_rows) == len(ai_shadow_rows)
    )
    record("manifest_row_count", expected_rows, f"manifest and four item CSVs contain {len(master_rows)} rows")
    record("creation_metadata", bool(manifest.get("created_at_utc") and manifest.get("source_commit") and manifest.get("script_commit") and manifest.get("script_sha256")), "manifest records creation time, source/script commit, and script checksum")

    report = {
        "schema_version": 1,
        "created_at_utc": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "stage": "agreement-pilot",
        "source_run": "v007-full-repro-2026",
        "pilot_manifest_sha256": _sha256_bytes(manifest_path.read_bytes()),
        "passed": not failures,
        "checks": checks,
        "counts": counts,
        "sampling": sampling,
        "inputs": {
            "identity_index_sha256": identity_hash,
            "repository_split_sha256": split_hash,
            "rule_family_map_sha256": mapping_hash,
        },
        "human_labels_present": not decisions_blank,
        "heldout_opened": not heldout_closed,
        "failures": failures,
    }
    _write_report(validation_dir, report)
    return report


